    // Lines of text from (x, y) down, in screen pixels. The font is monospaced, so text
    // laid out in columns with spaces stays in columns.
    public static Vertex[] Layout(IEnumerable<string> lines, float x, float y, float pixelSize, float lineGap)
    {
        var vertices = new List<Vertex>();
        float top = y;

        foreach (string line in lines)
        {
            float left = x;

            foreach (char c in line)
            {
                if (Glyphs.TryGetValue(char.ToUpperInvariant(c), out string[]? rows))
                    for (int row = 0; row < rows.Length; row++)
                        for (int column = 0; column < rows[row].Length; column++)
                            if (rows[row][column] == '1')
                                Shapes.AddRectangle(vertices, left + column * pixelSize, top + row * pixelSize, pixelSize, pixelSize);

                left += CellWidth * pixelSize;
            }

            top += CellHeight * pixelSize + lineGap;
        }

        return [.. vertices];
    }
